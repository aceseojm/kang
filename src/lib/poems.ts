export function getPoemsBySeason(season: SeasonId): Poem[] {
  return poems.filter((p) => p.season === season);
}

export function getPoem(season: SeasonId, slug: string): Poem | undefined {
  const decoded = decodeURIComponent(slug);
  return poems.find((p) => p.season === season && p.slug === decoded);
}

export function getAdjacentPoems(season: SeasonId, slug: string) {
  const decoded = decodeURIComponent(slug);
  const list = getPoemsBySeason(season);
  const index = list.findIndex((p) => p.slug === decoded);
  return {
    prev: index > 0 ? list[index - 1] : undefined,
    next: index >= 0 && index < list.length - 1 ? list[index + 1] : undefined,
  };
}
